// Готовые шаблоны обработки фото товара нейросетью.
// Каждый шаблон — это промпт, который отправляется в Gemini вместе с фото.
// Админ не видит и не редактирует сам текст промпта — только название и иконку.

export interface AiTemplate {
  id: string;
  label: string;
  icon: string;
  description: string;
  prompt: string;
  /** Соотношение сторон, которое нужно результату. */
  aspect: '1:1' | '4:3';
}

